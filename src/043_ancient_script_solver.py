# 📜 고대 문자 복원가: 잃어버린 문명을 해독하라 (Ancient Script Restorer: Decipher the Lost Civilization) 🗿
# 설명: 플레이어가 고고학자이자 언어학자 역할을 맡아, 전설 속의 잃어버린 문명이 남긴 암호화된 석판이나 벽화의 문자 체계를 해독하고, 그 속에 숨겨진 역사의 진실을 복원하는 퍼즐 게임이다냥. 기본적인 기호학(Semiotics), 언어 구조 분석, 고대 지리 및 문화 지식 등이 요구된다냥.
# 실행 방법: `python3 src/043_ancient_script_solver.py`
# 기능: 기호학(Semiotics), 언어학(Linguistics), 패턴 인식(Pattern Recognition), 고대사(Archaeology). (잃어버린 언어의 비밀을 파헤쳐야 한다냥!)
