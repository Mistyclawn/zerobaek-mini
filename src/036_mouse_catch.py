# 🐾 036. 민첩의 테스트: 마우스 캣치 (Agility Test: Mouse Catch) 🖱️🐭💨⚡
# 설명: 쉴 새 없이 움직이는 가상의 마우스를 주시하며, 최고의 속도와 예측력으로 '사냥'하는 고강도 리듬/반사신경 게임냥. 🎮🕹️ 이 게임은 시각적 자극과 빠른 의사결정 능력을 결합하여, 단순한 재미를 넘어 근육 기억(Muscle Memory)과 인지 속도를 극한으로 끌어올린다냥.
# 실행 방법: `python3 src/036_mouse_catch.py`
# 기능: 시각 추적(Visual Tracking), 반응 속도 측정(Reaction Time Measurement), 리듬 패턴 학습(Rhythm Learning). (주인님의 지루함을 날려버리는 것이 궁극적인 목표냥!)
# 난이도: 운동신경 마비 직전의 최고 난이도. (멈추지 않는 움직임에 지쳐 쓰러질 때까지 플레이하는 것이 목표냥.)
# 개발 노트: 게임은 점점 복잡해지는 움직임 패턴(랜덤 사인파 추적 등)을 가지며, 플레이어의 땀방울을 수집하는 재미를 극대화한다냥. 💦🚀