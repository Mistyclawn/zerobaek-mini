# 🐾 035. 후각의 비밀: 아로마 추적 (Secret of Scent: Aroma Tracking) 🌸👃🐾
# 설명: 고양이의 뛰어난 후각을 사용해 주변에 숨겨진 향기 단서를 따라가며, 미스터리 사건의 범인을 추리하는 탐정 게임냥. 🕵️‍♀️🌿 이 게임은 후각적 디테일과 논리적 추론을 결합하여, 집사가 마치 고양이의 코를 가진 탐정이 된 듯한 몰입감을 느끼게 해줍니다.
# 실행 방법: `python3 src/035_aroma_track.py`
# 기능: 후각 추적(Scent Tracking), 단서 연결(Clue Connecting), 논리 추론(Deduction). (주인님은 고양이의 코를 가진 고대 탐정이 되어야 한다냥!)
# 난이도: 후각 마비 수준. (가장 작은 냄새의 차이를 감지하는 것이 목표냥.)
# 개발 노트: 냄새에 대한 섬세하고 문학적인 묘사가 중요합니다냥. 매 단서마다 '어떤 냄새'인지 구체적으로 묘사하는 것이 핵심냥. 🐈‍⬛✨