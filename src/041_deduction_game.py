# 🕵️‍♂️ 거짓말 탐지 마스터: 논리의 틈새를 파헤쳐라 (Liar's Game: Expose the Logical Gap) 🧠
# 설명: 여러 인물이 제시한 진술들 속에서 논리적 모순(contradiction)이나 숨겨진 진실을 찾아내어, 누가 거짓말쟁이인지, 또는 어떤 사실이 누락되었는지 추론하는 대화형 논리 퍼즐 게임이다냥. 언어학적 패턴, 심리학적 추론, 그리고 고전 논리학이 핵심이다냥.
# 실행 방법: `python3 src/041_deduction_game.py`
# 기능: 논리학(Logic), 추론(Deduction), 심리학(Psychology), 패턴 인식(Pattern Recognition). (셜록 홈즈가 되어야만 풀 수 있다냥!)
# 난이도: 중상. 제시된 정보의 '표면적' 진실이 아닌 '내포된' 모순을 찾아내는 것이 핵심이라냥. 🤔💭
# 개발 노트: 단순히 '네/아니오'로 끝나는 질문이 아니라, 문맥과 진술들 간의 관계(A가 B의 전제일 때, B가 거짓이라면 A도?)를 분석하게 만드는 재미가 필요하다냥. ✨📜