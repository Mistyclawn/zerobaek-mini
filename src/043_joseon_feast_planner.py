# 🍚 조선시대 최고의 만찬 설계사: 궁중의 맛과 예의 (Joseon Dynasty Master Feasting Planner: Taste and Etiquette of the Palace)
# 설명: 플레이어는 궁중의 엄격한 격식과 계절의 재료를 이용해 최고의 만찬을 설계하는 시뮬레이션 게임이다냥. 식재료 조달(Supply Chain), 요리 순서(Culinary Sequence), 그리고 신분별 음식 격식(Status Etiquette) 등 다층적인 제약 조건 하에서 완벽한 만찬 코스를 짜내는 퍼즐이다냥.
# 실행 방법: `python3 src/043_joseon_feast_planner.py`
# 기능: 역사 시뮬레이션(Historical Simulation), 리소스 관리(Resource Management), 코스 구성 퍼즐(Course Puzzle), 격식 준수(Etiquette Constraint). (역사적 지식과 뛰어난 기획력이 필요한 영역이다냥!)
