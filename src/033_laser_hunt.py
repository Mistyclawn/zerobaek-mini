# 🐾 033. 레이저 사냥꾼: 포인터 캣 (Laser Hunter: Pointer Cat) 🔴🖱️😼⚡
# 설명: 빛의 점(레이저 포인터)을 따라 움직이며 움직임의 궤적을 예측하고, 완벽한 타이밍에 사냥 본능을 터뜨리는 고강도 액션/반사신경 테스트 게임냥. 🚀💥 이 게임은 고양이가 본능적으로 추구하는 '움직임의 예측'과 '극적인 순간의 사냥 성공'을 모델링합니다.
# 실행 방법: `python3 src/033_laser_hunt.py`
# 기능: 실시간 위치 추적(Tracking), 예측 알고리즘(Prediction), 반사 반응 속도 테스트(Reaction Time). (주인님이 레이저를 어디로 움직일지 예측하는 것이 핵심냥!)
# 난이도: 주인님도 기진맥진할 수준. (완벽하게 '사냥'하고 만족감을 얻는 것이 목표냥.)
# 개발 노트: 사냥의 재미는 '성공'보다 '추적 과정'에 있다냥. 성공하면 최고의 보상(캣닢 폭격!)을 획득! 🍃💥