# Gravity Puzzle Master
# 설명: 다양한 물리 법칙(중력, 탄성력, 자기장 등)이 적용되는 퍼즐 맵에서 오브젝트를 움직여 목표 지점까지 도달시키는 것을 목표로 하는 물리 기반 퍼즐 게임이다냥. 플레이어는 오브젝트의 질량, 충돌 반발력, 트랙의 곡률 등 물리적 매개변수를 조절하여 최적의 경로를 찾아야 한다냥.
# 실행 방법: `python3 src/040_gravity_puzzle_game.py`
# 기능: 물리 엔진(Physics Engine), 시스템 사고(Systems Thinking), 역학(Mechanics), 문제 해결(Problem Solving). (Newton의 3법칙 지식이 있으면 재미있을 거라냥!)
# 난이도: 상. 단순히 길을 찾는 것이 아니라, 오브젝트의 '행동' 자체를 예측하고 조작해야 하기에 깊은 통찰력이 필요하다냥. 🧩📐
# 개발 노트: 다양한 오브젝트와 장애물의 상호작용(예: 물체가 다른 물체를 밀치는 반작용)을 직관적으로 보여주는 비주얼 피드백이 핵심이 될 거라냥. ✨🌌