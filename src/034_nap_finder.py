# 😴 034. 최적의 낮잠 장소 찾기: 꿀잠 기계식 시뮬레이터 (Optimal Napping Spot Finder: Sweet Dream Machine Simulator) ☀️🛌💤
# 설명: 고양이에게 가장 완벽한 수면 환경을 찾아내는 시뮬레이션 게임냥. 온도, 습도, 햇빛 각도 등 복합적인 환경 요소를 고려하여 최적의 꿀잠 장소를 '과학적'으로 계산하고, 그 위치를 찾아내는 전략적 사고 테스트냥. 🔬✨ (사실은 냥이의 본능에 맡긴 것 같지만요...)
# 실행 방법: `python3 src/034_nap_finder.py`
# 기능: 환경 변수 분석(Variable Analysis), 최적화 알고리즘(Optimization), 휴식 능력 점수 계산(Rest Score).
# 난이도: 주인님도 편안하게 쉴 수 있는 수준. (최고의 힐링을 선사하는 것이 목표냥.)
