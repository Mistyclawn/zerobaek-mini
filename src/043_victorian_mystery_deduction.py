# 🕵️‍♀️ 빅토리안 미스터리 추리: 안개 속의 범죄 (Victorian Mystery Deduction: Crime in the Fog)

# 설명: 플레이어는 19세기 런던의 신비로운 명탐정이 되어, 의뢰받은 사건 현장을 조사한다냥. 복잡하게 얽힌 목격자들의 증언, 숨겨진 편지, 현장의 미세한 증거물 등을 조합하여 사건의 진실을 파헤치는 스토리 기반의 추리 게임이다냥. 전형적인 추론 퍼즐과 관계망 그래프 분석이 핵심이다냥.
# 실행 방법: `python3 src/043_victorian_mystery_deduction.py`
# 기능: 추리(Deduction), 논리 퍼즐(Logic Puzzle), 인물 관계망 분석(Graph Theory), 시간 순서 파악(Chronology). (치밀한 관찰력과 인간 심리에 대한 깊은 이해가 필요한 영역이다냥!)
# 난이도: 중상. 단편적인 단서만으로는 진실에 닿지 못하며, '누가, 무엇을, 왜 거짓말했는지'를 파악하는 심리적 깊이가 요구된다냥. 🧐🧩
# 개발 노트: 게임의 몰입감을 높이기 위해 당시의 분위기(안개, 가스등 불빛 등)를 시각적 요소로 풍부하게 구현하면 좋겠다냥. '진범은 항상 그 자리에 있었다'는 느낌을 주는 것이 핵심이다냥.
